//! Pi-specific helpers.
//!
//! Pi (https://pi.dev) is embedded as its interactive TUI, like Claude Code.
//! Unlike Claude, it has no shell-command hook system; its extension points
//! are in-process TypeScript modules. To get a *real* waiting/working status
//! signal (instead of guessing from PTY output), corral ships a tiny status
//! extension, writes it to its data dir, and spawns pi with
//! `--extension <path>`.
//!
//! The extension talks to corral over the same Unix socket Claude's hooks use
//! (`crate::hooks::socket_path`), but connects directly with Node's `net`
//! module rather than shelling out to `corral notify-hook` — the spawned pi
//! process already inherits `CORRAL_HOOK_SOCKET`, and corral additionally sets
//! `CORRAL_SESSION_ID` to this worktree's registry key so the extension needs
//! no `cwd`-to-worktree resolution or `corral` binary on `PATH`.

use std::path::{Path, PathBuf};

use crate::error::Result;
use crate::paths::data_root;

/// Filename of the installed status extension under `<data_root>/pi/`.
const STATUS_EXTENSION_FILENAME: &str = "corral-status.ts";

/// The status extension source. Deliberately dependency-free (only Node's
/// built-in `net`) and typed loosely, so it loads under pi's `jiti` runtime
/// without needing a `package.json` or any installed packages.
///
/// Event mapping mirrors Claude Code's hook semantics: an agent loop starting
/// (or fresh user input arriving) means *working*; the point at which pi has
/// fully settled — no automatic retry, compaction, or queued continuation
/// pending — means *waiting for the user*. Pi has no built-in background-job
/// concept (the bundled subagent example runs child `pi` processes
/// synchronously inside a tool call), and `agent_settled` already waits for
/// every automatic continuation to drain, so no extra background-work
/// tracking is needed here.
const STATUS_EXTENSION: &str = r#"// Generated by corral. Reports this session's working/waiting state to
// corral's hook socket so the status dot, sleep inhibitor, and idle timeout
// reflect the real agent state. Inert when not launched by corral.
import { connect } from "node:net";

export default function (pi) {
  const socket = process.env.CORRAL_HOOK_SOCKET;
  const id = process.env.CORRAL_SESSION_ID;
  if (!socket || !id) return;

  const report = (event) => {
    try {
      const conn = connect(socket);
      conn.on("error", () => conn.destroy());
      conn.on("connect", () => {
        conn.end(JSON.stringify({ id, event, summary: null }) + "\n");
      });
    } catch {
      // Best-effort: a dropped update only affects the status dot.
    }
  };

  pi.on("agent_start", () => report("working"));
  pi.on("input", () => report("working"));
  pi.on("agent_settled", () => report("waiting"));
}
"#;

/// Install (or refresh) the pi status extension under `<data_root>/pi/`,
/// returning the file path to pass to `--extension`.
///
/// Idempotent: the file is only rewritten when its contents differ, so
/// repeatedly starting sessions doesn't churn the filesystem.
pub fn ensure_status_extension() -> Result<PathBuf> {
    write_status_extension(&data_root()?.join("pi"))
}

/// [`ensure_status_extension`] with an explicit directory, so the write
/// behavior is testable without touching `$XDG_DATA_HOME`.
fn write_status_extension(dir: &Path) -> Result<PathBuf> {
    std::fs::create_dir_all(dir)?;
    let path = dir.join(STATUS_EXTENSION_FILENAME);
    if std::fs::read_to_string(&path).ok().as_deref() != Some(STATUS_EXTENSION) {
        std::fs::write(&path, STATUS_EXTENSION)?;
    }
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_the_extension_and_is_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        let path = write_status_extension(dir.path()).unwrap();

        assert_eq!(path, dir.path().join(STATUS_EXTENSION_FILENAME));
        let written = std::fs::read_to_string(&path).unwrap();
        assert!(written.contains("agent_settled"));
        assert!(written.contains("CORRAL_SESSION_ID"));
    }

    #[test]
    fn rewrites_the_extension_when_its_contents_change() {
        let dir = tempfile::tempdir().unwrap();
        let path = write_status_extension(dir.path()).unwrap();
        std::fs::write(&path, "stale").unwrap();

        write_status_extension(dir.path()).unwrap();

        assert_eq!(std::fs::read_to_string(&path).unwrap(), STATUS_EXTENSION);
    }
}
